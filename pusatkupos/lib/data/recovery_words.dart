const int recoveryWordCount = 12;
const int recoveryMinWords = 6;

/// Normalisasi frasa: huruf kecil dan satu spasi. Frasa yang disalin dari
/// catatan dengan baris baru atau spasi ganda tetap membuka escrow yang sama.
String normalizeRecoveryPhrase(String raw) =>
    raw.toLowerCase().trim().split(RegExp(r'\s+')).join(' ');

String generateRecoveryPhrase(List<int> entropyBytes) {
  final trimmed = entropyBytes.length >= recoveryWordCount
      ? entropyBytes.sublist(0, recoveryWordCount)
      : List<int>.from(entropyBytes);
  return trimmed.map((value) => recoveryWords[value & 0xFF]).join(' ');
}

bool isRecoveryPhraseShape(String raw) {
  final phrase = normalizeRecoveryPhrase(raw);
  if (phrase.isEmpty) return false;
  return phrase.split(' ').length >= recoveryMinWords;
}
